// QA do menu e do quiz em 390x844. Uso: node scripts/qa-quiz.cjs <pasta-saida> (com `npm run preview` rodando)
const { chromium } = require('playwright')
;(async () => {
  const S = process.argv[2]
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 390, height: 844 } })
  const erros = []
  p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) erros.push(m.text()) })
  p.on('pageerror', (e) => erros.push(String(e)))
  let popup = null
  p.context().on('page', (pg) => { popup = pg.url() })
  await p.goto('http://localhost:4173/')
  await p.waitForTimeout(1000)
  await p.click('.hamburguer'); await p.waitForTimeout(900); await p.screenshot({ path: S + '/q0.png' })
  await p.keyboard.press('Escape'); await p.waitForTimeout(700)
  console.log('foco pós-menu:', await p.evaluate(() => document.activeElement.className))
  await p.click('.hero__acoes .botao'); await p.waitForTimeout(250); await p.screenshot({ path: S + '/q1.png' })
  await p.waitForTimeout(900)
  await p.click('.quiz__continuar'); await p.waitForTimeout(500); await p.screenshot({ path: S + '/q2.png' })
  await p.fill('input', 'Maria Souza'); await p.keyboard.press('Enter'); await p.waitForTimeout(600)
  const ins = await p.$$('input'); await ins[0].fill('Clínica Bella'); await ins[1].fill('Poços de Caldas'); await p.keyboard.press('Enter'); await p.waitForTimeout(600)
  const w = await p.$$('input'); await w[0].fill('3599'); await p.keyboard.press('Enter'); await p.waitForTimeout(500); await p.screenshot({ path: S + '/q3.png' })
  await w[0].fill('35999998888'); await w[1].fill('clinicabella'); await p.keyboard.press('Enter'); await p.waitForTimeout(700); await p.screenshot({ path: S + '/q4.png' })
  await p.click('text=Estética e beleza'); await p.waitForTimeout(900)
  await p.click('.quiz .botao--contorno'); await p.waitForTimeout(600)
  console.log('área preservada:', await p.evaluate(() => document.querySelector('.opcao--marcada')?.textContent))
  await p.click('.quiz__continuar'); await p.waitForTimeout(600)
  await p.click('text=Não tenho'); await p.waitForTimeout(900); await p.screenshot({ path: S + '/q5.png' })
  await p.click('.resumo__enviar'); await p.waitForTimeout(1500); await p.screenshot({ path: S + '/q6.png' })
  console.log('popup aberto:', !!popup, '| link:', decodeURIComponent(await p.getAttribute('.sucesso a', 'href')))
  await p.keyboard.press('Escape'); await p.waitForTimeout(400)
  console.log('quiz fechado:', !(await p.$('.quiz')), '| foco:', await p.evaluate(() => document.activeElement.textContent), '| travado:', await p.evaluate(() => document.documentElement.classList.contains('travado')))
  console.log('erros', JSON.stringify(erros))
  await b.close()
})()
